export function toAscii(string){
    let top = "";
    let mid = "";
    let bot = "";

    for (let i = 0; i < string.length; i++){
        if (string[i] in asciiFont){
            const ascii_char = asciiFont[string[i]];
            top = top + ascii_char[0];
            mid = mid + ascii_char[1];
            bot = bot + ascii_char[2];
        }else{
            top = top + asciiFont["?"][0];
            mid = mid + asciiFont["?"][1];
            bot = bot + asciiFont["?"][2];
        }
        
    }

    return `${top}\n${mid}\n${bot}`;
}




