let currentTommy = 0

export function updateTommy(){
    if (Math.floor(Math.random()*501) == 0){
        currentTommy += 1
        if (currentTommy == TommyFrames.length){
            currentTommy = 0
        }
    }

    return TommyFrames[currentTommy]
}


export function renderAscii(text) {
    // Protect ASCII characters that HTML treats specially
    let html = text
        .replaceAll("&", "&amp;")
        .replaceAll("<", "&lt;")
        .replaceAll(">", "&gt;");

    // Convert our color markers into HTML
    html = html
        .replaceAll("[[green]]", '<span class="tommy-green">')
        .replaceAll("[[/green]]", "</span>")
        .replaceAll("[[brown]]", '<span class="tommy-brown">')
        .replaceAll("[[/brown]]", "</span>");

    return html;
}