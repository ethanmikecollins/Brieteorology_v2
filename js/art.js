export function renderTree(tree) {
    let html = "";
    let green = false;

    for (let i = 0; i < tree.length; i++) {

        const char = tree[i];

        if (char === " " || char === "\n") {
            html += char;
            continue;
        }

        let escaped = char
            .replaceAll("&", "&amp;")
            .replaceAll("<", "&lt;")
            .replaceAll(">", "&gt;");

        if (char === "#" || char === "&" || char === "%") {
            html += `<span class="tree-char tree-leaf">${escaped}</span>`;
        } else {
            html += `<span class="tree-char">${escaped}</span>`;
        }
    }

    return html;
}


export function renderPrecip(frame) {
  let html = "";

  for (let i = 0; i < frame.length; i++){
    const char = frame[i];
    
    if (char == " "){
      html += char;
    }else if (char == "|" || char == "│"){
      html += `<span class="rain-char">${char}</span>`;
    }else{
      html += `<span class="snow-char">${char}</span>`;
    }
  }

  return html;
}


